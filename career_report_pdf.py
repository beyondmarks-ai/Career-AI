"""Create polished, in-memory PDF exports for career reports."""

from __future__ import annotations

import io
from html import escape
from typing import Any

from reportlab.lib import colors
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (
    BaseDocTemplate,
    Frame,
    KeepTogether,
    PageTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle,
)


NAVY = colors.HexColor("#0B2545")
BLUE = colors.HexColor("#2166F3")
CYAN = colors.HexColor("#43C7DA")
INK = colors.HexColor("#132238")
MUTED = colors.HexColor("#607087")
PALE = colors.HexColor("#F3F7FD")
LINE = colors.HexColor("#DDE7F3")


def _text(value: Any, limit: int = 2000) -> str:
    return escape(str(value or "").strip()[:limit])


def _page(canvas, doc):
    canvas.saveState()
    width, height = A4
    canvas.setFillColor(NAVY)
    canvas.rect(0, height - 17 * mm, width, 17 * mm, fill=1, stroke=0)
    canvas.setFillColor(CYAN)
    canvas.circle(17 * mm, height - 8.5 * mm, 4.2 * mm, fill=1, stroke=0)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 8)
    canvas.drawCentredString(17 * mm, height - 10 * mm, "CA")
    canvas.setFont("Helvetica-Bold", 10)
    canvas.drawString(25 * mm, height - 10.5 * mm, "CAREER AI")
    canvas.setFillColor(MUTED)
    canvas.setFont("Helvetica", 8)
    canvas.drawString(18 * mm, 10 * mm, "Private career report - generated by Career AI")
    canvas.drawRightString(width - 18 * mm, 10 * mm, f"Page {doc.page}")
    canvas.restoreState()


def build_career_report_pdf(report: dict[str, Any]) -> bytes:
    """Return a PDF representation of a validated client career report."""
    stream = io.BytesIO()
    doc = BaseDocTemplate(
        stream,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=18 * mm,
        topMargin=25 * mm,
        bottomMargin=18 * mm,
        title="Career AI Report",
        author="Career AI",
    )
    frame = Frame(doc.leftMargin, doc.bottomMargin, doc.width, doc.height, id="content")
    doc.addPageTemplates(PageTemplate(id="career-report", frames=[frame], onPage=_page))

    base = getSampleStyleSheet()
    title = ParagraphStyle("Title", parent=base["Title"], fontName="Helvetica-Bold", fontSize=23, leading=28, textColor=NAVY, alignment=TA_CENTER, spaceAfter=7)
    subtitle = ParagraphStyle("Subtitle", parent=base["BodyText"], fontSize=10, leading=15, textColor=MUTED, alignment=TA_CENTER, spaceAfter=15)
    heading = ParagraphStyle("Heading", parent=base["Heading2"], fontName="Helvetica-Bold", fontSize=14, leading=18, textColor=NAVY, spaceBefore=13, spaceAfter=7)
    body = ParagraphStyle("Body", parent=base["BodyText"], fontSize=9.5, leading=14, textColor=INK)
    item = ParagraphStyle("Item", parent=body, leftIndent=12, firstLineIndent=-8, spaceAfter=6)
    small = ParagraphStyle("Small", parent=body, fontSize=8, leading=11, textColor=MUTED)

    candidate = _text(report.get("candidate_name"), 120)
    role = _text(report.get("target_role"), 120) or "Career target"
    story = [
        Spacer(1, 4 * mm),
        Paragraph(f"{candidate + ' - ' if candidate else ''}Career Readiness Report", title),
        Paragraph(f"Target role: <b>{role}</b>", subtitle),
    ]

    score_cells = []
    for label, key, color in (
        ("OVERALL READINESS", "overall_score", BLUE),
        ("ATS COMPATIBILITY", "ats_score", colors.HexColor("#16A085")),
        ("ROLE MATCH", "role_match_score", colors.HexColor("#E8922F")),
    ):
        try:
            score = max(0, min(100, int(report.get(key, 0))))
        except (TypeError, ValueError):
            score = 0
        score_cells.append(
            [Paragraph(label, small), Paragraph(f"<font size='19'><b>{score}</b></font>/100", body)]
        )
    scores = Table([score_cells], colWidths=[doc.width / 3] * 3, hAlign="CENTER")
    scores.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), PALE),
        ("BOX", (0, 0), (-1, -1), 0.7, LINE),
        ("INNERGRID", (0, 0), (-1, -1), 0.7, LINE),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 9),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 9),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
    ]))
    story.extend([scores, Paragraph("Executive summary", heading), Paragraph(_text(report.get("summary")), body)])

    def add_list(section: str, values: Any):
        clean = values if isinstance(values, list) else []
        story.append(Paragraph(section, heading))
        if not clean:
            story.append(Paragraph("No items identified.", body))
        for value in clean[:12]:
            story.append(Paragraph(f"<font color='#2166F3'>•</font> {_text(value, 700)}", item))

    add_list("Key strengths", report.get("strengths"))
    add_list("Priority improvements", report.get("improvements"))
    add_list("Missing role keywords", report.get("missing_keywords"))

    story.append(Paragraph("Skills worth building next", heading))
    skills = report.get("skill_recommendations")
    for skill in (skills if isinstance(skills, list) else [])[:8]:
        if not isinstance(skill, dict):
            continue
        block = [
            Paragraph(f"<b>{_text(skill.get('name'), 120)}</b>  <font color='#607087'>({_text(skill.get('priority'), 30)} priority)</font>", body),
            Paragraph(_text(skill.get("reason"), 600), body),
            Paragraph(f"<font color='#2166F3'><b>Next:</b></font> {_text(skill.get('next_step'), 500)}", small),
            Spacer(1, 3 * mm),
        ]
        story.append(KeepTogether(block))

    add_list("Focused action plan", report.get("action_plan"))
    story.extend([
        Spacer(1, 5 * mm),
        Paragraph("This report is career guidance based on the submitted resume. Review recommendations against your experience before applying them.", small),
    ])
    doc.build(story)
    return stream.getvalue()
